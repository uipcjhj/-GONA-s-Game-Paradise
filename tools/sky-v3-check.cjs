// 3차 개선 검수: 타이틀 → 선택 → 플레이(무기 레벨·필살기 7종·보스 약점/장갑·클리어) + 오디오 상태·404·콘솔 오류
// 사용: NODE_PATH=$(npm root -g) node tools/sky-v3-check.cjs <url> <outdir> [w] [h]
const { chromium } = require('playwright');
const [url, out, W = '393', H = '636'] = process.argv.slice(2);
(async () => {
  const b = await chromium.launch({ args: ['--autoplay-policy=user-gesture-required'] });
  const ctx = await b.newContext({ viewport: { width: +W, height: +H }, deviceScaleFactor: 2, isMobile: true, hasTouch: true, userAgent: 'Mozilla/5.0 (iPhone; CPU iPhone OS 17_5 like Mac OS X) AppleWebKit/605.1.15 (KHTML, like Gecko) Version/17.5 Mobile/15E148 Safari/604.1' });
  const page = await ctx.newPage();
  const bad = [], errs = [];
  page.on('response', (r) => r.status() >= 400 && bad.push(r.status() + ' ' + r.url()));
  page.on('pageerror', (e) => errs.push(e.message));
  page.on('console', (m) => m.type() === 'error' && errs.push(m.text()));
  const tag = `${W}x${H}`;
  const shot = (n) => page.screenshot({ path: `${out}/${tag}-${n}.png` });
  const A = () => page.evaluate(() => window.__skyAudio());
  const D = () => page.evaluate(() => window.__sky.debug());
  await page.goto(url);
  await page.waitForSelector('.ttl-start');
  await page.waitForTimeout(1600);
  console.log('타이틀 (터치 전 오디오)', JSON.stringify(await A()));
  await shot('01-title');
  await page.touchscreen.tap(20, 300);
  await page.waitForTimeout(1200);
  console.log('터치 후', JSON.stringify(await A()));
  await page.tap('.ttl-start');
  await page.waitForSelector('.sel-art');
  await page.waitForTimeout(900);
  console.log('선택 화면', JSON.stringify(await A()));
  await shot('02-select');
  const fams = ['mom', 'dad', 'imo', 'halmeoni', 'halabeoji', 'samchon'];
  const only = process.env.FAMS ? process.env.FAMS.split(',') : fams;
  for (const f of only) {
    const i = fams.indexOf(f);
    await page.tap(`.sel-roster li:nth-child(${i + 1}) button`);
    await page.waitForTimeout(200);
    await page.tap('.sky-btn-go');
    await page.waitForSelector('.sky-canvas');
    await page.waitForTimeout(2600);
    await page.evaluate(() => { window.__sky.cheat('god'); window.__sky.cheat('power'); });
    await page.waitForTimeout(2200);
    if (f === only[0]) { await shot('03-play-lv4'); console.log('플레이', JSON.stringify(await A())); }
    await page.evaluate(() => window.__sky.cheat('gauge'));
    await page.waitForTimeout(150);
    const btn = await page.$('.sky-sp');
    console.log(f, '버튼 ready', await btn.evaluate((e) => e.classList.contains('ready')));
    await page.tap('.sky-sp');
    await page.waitForTimeout(250);
    await shot(`10-sp-${f}-cutin`);
    await page.waitForTimeout(f === 'halabeoji' ? 1900 : 900);
    await shot(`11-sp-${f}-effect`);
    const d = await D();
    console.log(f, '필살 진행', JSON.stringify({ sp: d.sp, pb: d.pbullets, hp: d.hp }));
    await page.waitForTimeout(2500);
    await page.tap('.sky-pause');
    await page.waitForSelector('.sky-overlay');
    if (f === only[0]) await shot('12-pause');
    await page.tap('text=동료 바꾸기');
    await page.waitForSelector('.sel-art');
  }
  // 고나 폭탄 + 보스전
  await page.tap('.sky-btn-go');
  await page.waitForSelector('.sky-canvas');
  await page.waitForTimeout(2600);
  await page.evaluate(() => { window.__sky.cheat('god'); window.__sky.cheat('power'); });
  await page.tap('.sky-bomb');
  await page.waitForTimeout(300);
  await shot('20-bomb-cutin');
  await page.waitForTimeout(800);
  await shot('21-bomb-roar');
  await page.evaluate(() => window.__sky.cheat('boss'));
  await page.waitForTimeout(1500);
  await shot('22-warning');
  console.log('경고 중 오디오', JSON.stringify(await A()));
  for (let k = 0; k < 60; k++) { const d = await D(); if (d.boss > 0 && d.t > 60) break; await page.waitForTimeout(150); }
  await page.waitForTimeout(1200);
  console.log('보스전 오디오', JSON.stringify(await A()));
  await shot('23-boss');
  await page.evaluate(() => { const s = window.__sky; s.boss.hp = s.boss.max * 0.3; });
  await page.waitForTimeout(2500);
  await shot('24-boss-phase3');
  await page.evaluate(() => window.__sky.cheat('killboss'));
  await page.waitForTimeout(900);
  await shot('25-boss-break');
  await page.waitForSelector('text=STAGE CLEAR', { timeout: 15000 });
  await page.waitForTimeout(400);
  console.log('클리어 오디오', JSON.stringify(await A()));
  await shot('26-clear');
  await page.tap('text=타이틀로');
  await page.waitForSelector('.ttl-start');
  await page.waitForTimeout(600);
  console.log('타이틀 복귀 오디오', JSON.stringify(await A()));
  await page.tap('.ttl-map');
  await page.waitForTimeout(600);
  console.log('월드맵 복귀', await page.locator('.frame').count(), JSON.stringify(await A()));
  console.log('실패 요청', bad.length ? bad : '없음');
  console.log('콘솔 오류', errs.length ? errs : '없음');
  await b.close();
})();
